--- Time of the last reaction per victim, keyed by entity id.
-- @table RecentHits
HorseCollisionMod.RecentHits = {}

--- Last time each entity was reported as a miss, keyed by entity id.
HorseCollisionMod.RecentRejections = {}

--- Recent horse speeds, newest last, for spotting deceleration on impact.
--
-- Speed is sampled once per tick at the top of the loop. A collision slows the
-- horse, so if a victim only enters the footprint on the tick after contact
-- begins, the speed read is the speed after the impact rather than the speed
-- that caused it. That would explain a gallop being recorded as a walk, and it
-- would also drop the reaction entirely whenever the loss takes the horse under
-- `SpeedWalk`, because that test returns before any entity is examined.
--
-- Kept deliberately short. Half a second of history is enough to see a
-- deceleration and not so much that an earlier gallop colours a later walk.
HorseCollisionMod.SpeedHistory = {}

HorseCollisionMod.SpeedHistorySize = 10

local function GetTimeMs()
	return System.GetCurrTime() * 1000
end

--- Magnitude of a CryEngine vector.
-- @tparam ?table v vector with x, y and z components, or nil
-- @treturn number length, or 0 when v is nil
local function GetVectorLength(v)
	if not v then
		return 0
	end

	return math.sqrt((v.x * v.x) + (v.y * v.y) + (v.z * v.z))
end

--- Records a speed sample and returns the highest in recent history.
--
-- @tparam number speed the current sample, in meters per second
-- @treturn number the highest sample still in the window
function HorseCollisionMod:TrackSpeed(speed)
	local history = self.SpeedHistory

	history[#history + 1] = speed

	while #history > self.SpeedHistorySize do
		table.remove(history, 1)
	end

	local peak = speed

	for _, sample in ipairs(history) do
		if sample > peak then
			peak = sample
		end
	end

	return peak
end

--- Logs why a candidate was passed over, at most once per second per entity.
--
-- Every rejection in the detection loop is silent, so an impact that produces
-- no reaction is indistinguishable from one that was never detected. This
-- names the reason.
--
-- Rate limited because the loop runs about twenty times a second and the
-- detection sphere returns everything nearby, including crates and doors.
--
-- @tparam table npc the entity that was rejected
-- @tparam string reason short label for which test rejected it
-- @tparam string detail the measurement behind that decision
function HorseCollisionMod:LogRejection(npc, reason, detail)
	if not self.Config.DiagnoseMisses then
		return
	end

	local id = tostring(npc and npc.id or "?")
	local now = GetTimeMs()
	local last = self.RecentRejections[id]

	if last and (now - last) < 1000 then
		return
	end

	self.RecentRejections[id] = now

	local name = "?"

	pcall(function()
		name = npc:GetName() or "?"
	end)

	self:Log("Miss " .. reason .. " name=" .. tostring(name)
			.. " " .. tostring(detail))
end


--- Current time in milliseconds.
-- @treturn number milliseconds since the game session started
--- Writes a prefixed line to kcd.log when telemetry is enabled.
-- @tparam string message text to log
function HorseCollisionMod:Log(message)
	if not self.Config.LogTelemetry then
		return
	end

	System.LogAlways("[HorseCollisionMod] " .. tostring(message))
end

--- Resolves a speed to its gait name.
-- @tparam number speed horse speed in meters per second
-- @treturn string one of "Gallop", "Trot", "Walk" or "Idle"
function HorseCollisionMod:GetSpeedTier(speed)
	local cfg = self.Config

	if speed >= cfg.SpeedGallop then
		return "Gallop"
	end

	if speed >= cfg.SpeedTrot then
		return "Trot"
	end

	if speed >= cfg.SpeedWalk then
		return "Walk"
	end

	return "Idle"
end

--- Posts the native `hitReaction` message to the victim's brain.
--
-- This is what makes the vanilla collision bark, perception and crime
-- handling fire, so the reaction still feels like part of the game rather
-- than something bolted on. It does **not** drive animation.
--
-- Delivery is best effort. The receiving handler is declared `Atomic="true"`
-- and drops messages when busy, so nothing here may depend on a given
-- message arriving.
--
-- @tparam table npc victim entity
-- @tparam userdata horseWuid WUID of the horse, sent as the attacker
-- @tparam number strength a `HitReactionStrength` value
function HorseCollisionMod:SendHitReaction(npc, horseWuid, strength)
	if not self.Config.SendHitReaction then
		return
	end

	pcall(function()
		-- Brain messages carry their arguments as a "key(value), key(value)"
		-- string rather than a table.
		local values = "hitStrength(" .. tostring(strength)
				.. "), hitType(" .. tostring(self.HitReactionType.Collision) .. ")"

		-- The horse is named as the attacker, not Henry. That matches what
		-- the engine does for a trample, and the victim's brain resolves the
		-- rider from the horse itself when assigning blame.
		if horseWuid and Framework and Framework.WUIDToMsg then
			values = "attacker(" .. Framework.WUIDToMsg(horseWuid) .. "), " .. values
		end

		XGenAIModule.SendMessageToEntity(npc.id, "hitReaction", values)
	end)
end

--- Tests whether a victim is actually under the horse.
--
-- The sphere search is a broad-phase cull and nothing more. A horse is about
-- two meters long and under a meter wide, so a sphere around its origin also
-- catches people walking alongside or trailing behind it, which is what makes
-- collisions feel like they reach too far.
--
-- This narrows the sphere to an oriented box: the victim must be within the
-- horse's width laterally, between its rear and front reach along its facing,
-- and at a comparable height. The front reach is extended by the distance the
-- horse travels in one tick so that fast victims are not missed between
-- frames.
--
-- @tparam table npc victim entity
-- @tparam table horsePos world position of the horse
-- @tparam table horseForward horse facing, unit vector
-- @tparam number speed horse speed in meters per second
-- @treturn boolean true when the victim is inside the footprint
function HorseCollisionMod:IsInHorseFootprint(npc, horsePos, horseForward, speed)
	local cfg = self.Config
	local npcPos = nil

	pcall(function()
		npcPos = npc:GetPos()
	end)

	if not npcPos or not horsePos or not horseForward then
		return false
	end

	local dx = npcPos.x - horsePos.x
	local dy = npcPos.y - horsePos.y
	local dz = npcPos.z - horsePos.z

	-- Rejects anyone on a bridge overhead or in a cellar below, who would
	-- otherwise pass the flat two-dimensional test.
	if math.abs(dz) > cfg.HorseMaxVerticalDiff then
		return false
	end

	-- Distance along the horse's facing, and perpendicular to it. The
	-- perpendicular is taken directly from the forward vector rather than
	-- asking the engine for a second axis, so the two cannot disagree.
	local forwardDistance = (horseForward.x * dx) + (horseForward.y * dy)
	local lateralDistance = math.abs((horseForward.y * dx) - (horseForward.x * dy))

	local sweepExtra = speed * cfg.TickSeconds * cfg.SweepMultiplier

	if sweepExtra > cfg.MaxSweepExtra then
		sweepExtra = cfg.MaxSweepExtra
	end

	local inside = forwardDistance >= -cfg.HorseRearReach
			and forwardDistance <= (cfg.HorseFrontReach + sweepExtra)
			and lateralDistance <= cfg.HorseHalfWidth

	local detail = "fwd=" .. string.format("%.2f", forwardDistance)
			.. " lat=" .. string.format("%.2f", lateralDistance)
			.. " dz=" .. string.format("%.2f", dz)
			.. " sweep=" .. string.format("%.2f", sweepExtra)
			.. " limits=" .. string.format("%.2f/%.2f/%.2f",
					cfg.HorseFrontReach + sweepExtra, cfg.HorseHalfWidth,
					cfg.HorseMaxVerticalDiff)

	if inside then
		self:Log("Footprint " .. detail)
	end

	return inside, detail
end


--- Measurements for a candidate the footprint test rejected.
--
-- Same geometry as the test itself rather than a second copy of it, so the
-- numbers reported are the numbers the decision was made on.
--
-- @treturn string the distances and the limits they were checked against
function HorseCollisionMod:FootprintDetail(npc, horsePos, horseForward, speed)
	local _, detail = self:IsInHorseFootprint(npc, horsePos, horseForward, speed)

	return detail or "unmeasurable"
end

--- Works out which side of the victim the impact lands on.
--
-- The stagger clips are authored relative to the NPC's facing, so the impact
-- has to be expressed in the victim's own frame. Using the horse's frame
-- instead makes NPCs stagger into the horse rather than away from it.
--
-- The impact is derived from the horse's **direction of travel**, not its
-- position. Position is ambiguous at the moment of contact, when the horse
-- is effectively on top of the victim and a centimeter either way flips the
-- answer. Travel direction is stable, and it is what actually decides which
-- side of the body is struck: a horse moving north hits the south face of
-- whoever is in front of it.
--
-- @tparam table npc victim entity
-- @tparam table velocity horse velocity vector
-- @tparam number speed horse speed in meters per second
-- @treturn string one of "so_forward", "so_back", "so_left", "so_right"
function HorseCollisionMod:GetImpactDir(npc, velocity, speed)
	local forward = nil

	pcall(function()
		if npc.GetDirectionVector then
			forward = npc:GetDirectionVector(1)
		end
	end)

	if not forward or not velocity or speed <= 0 then
		return "so_forward"
	end

	-- The blow arrives from the direction the horse came from, which is the
	-- opposite of its travel. Flattened to the ground plane, since a rider
	-- is always above a pedestrian and the height would bias every result.
	local fromX = -velocity.x / speed
	local fromY = -velocity.y / speed

	-- Projected onto the victim's axes: dot is how much the blow comes from
	-- ahead of them (negative means from behind), cross is how much it comes
	-- from their left (negative means their right).
	local dot = (forward.x * fromX) + (forward.y * fromY)
	local cross = (forward.x * fromY) - (forward.y * fromX)

	-- The larger magnitude wins, which snaps the blow to the nearest of the
	-- four authored clips. Comparing magnitudes rather than testing a fixed
	-- angle means a glancing hit still resolves sensibly.
	if math.abs(dot) >= math.abs(cross) then
		if dot >= 0 then
			return "so_forward"
		end

		return "so_back"
	end

	if cross >= 0 then
		return "so_left"
	end

	return "so_right"
end

--- Plays the walk-speed stagger on a victim.
--
-- Calls `actor:StartInteractiveActionByName` with one of the `hcm_stagger_*`
-- names this mod adds to the animation database. See the module header for
-- why this is the only call that works.
--
-- The return value reports whether the call was accepted, which is **not**
-- the same as the animation playing: an unrecognized name is accepted and
-- then aborts within a frame. Only in-game observation confirms playback.
--
-- @tparam table npc victim entity
-- @tparam table velocity horse velocity vector
-- @tparam number speed horse speed in meters per second
-- @treturn boolean true when the call was accepted without error
function HorseCollisionMod:PlayStagger(npc, velocity, speed)
	if not npc.actor or type(npc.actor.StartInteractiveActionByName) ~= "function" then
		return false
	end

	-- GetImpactDir speaks the engine's "so_" vocabulary; the database entries
	-- this mod adds are named without that prefix, so strip it.
	local dir = self:GetImpactDir(npc, velocity, speed)
	local action = "hcm_stagger_" .. string.gsub(dir, "so_", "")


	-- Gender is logged because the female animation set has no
	-- AnimationControlled fragment, so female victims accept the call and
	-- play nothing. Without this the misses look random.
	local gender = "?"

	pcall(function()
		if npc.soul and npc.soul.GetGender then
			gender = tostring(npc.soul:GetGender())
		end
	end)

	local ok, err = pcall(function()
		-- The second argument is the object being interacted with. There is
		-- no object in a collision, so the victim is passed as its own
		-- target; the animation needs no alignment to anything external.
		npc.actor:StartInteractiveActionByName(action, npc.id, true, 1)
	end)

	self:Log("Stagger action=" .. action
			.. " gender=" .. gender
			.. " ok=" .. tostring(ok)
			.. " err=" .. tostring(err))

	return ok
end

--- Knocks a victim down with a physics ragdoll.
--
-- Used at trot and gallop. `actor:Fall` switches the victim to a ragdoll,
-- after which an impulse can be applied. Impulses are ignored on an upright,
-- animation-driven actor, so the order matters and the impulse is deferred
-- by a tick.
--
-- @tparam table npc victim entity
-- @tparam table velocity horse velocity vector
-- @tparam number speed horse speed in meters per second
-- @tparam number impulseScale multiplier on the configured impulse, 0 to 1
function HorseCollisionMod:Ragdoll(npc, velocity, speed, impulseScale)
	pcall(function()
		if npc.actor then
			npc.actor:Fall({x=0, y=0, z=0}, true)
		end
	end)

	local k_back = self.Config.Knockback * impulseScale
	local k_up = self.Config.Uplift * impulseScale

	if k_back <= 0 and k_up <= 0 then
		return
	end

	pcall(function()
		local hitPos = {x=0, y=0, z=0}
		local dir = {x=1, y=0, z=0}

		if npc.GetPos then
			hitPos = npc:GetPos()
		end

		-- Lift the application point to roughly chest height so the victim
		-- rotates over the impact instead of having their feet swept.
		hitPos.z = hitPos.z + 1.0

		if speed > 0 and velocity then
			dir.x = velocity.x / speed
			dir.y = velocity.y / speed
			dir.z = 0
		end

		-- Forward push and upward lift are combined into one vector, then
		-- split back into a unit direction and a magnitude, because
		-- AddImpulse wants those as separate arguments.
		local combined = { x = dir.x * k_back, y = dir.y * k_back, z = k_up }
		local impulseMag = math.sqrt((combined.x * combined.x)
				+ (combined.y * combined.y)
				+ (combined.z * combined.z))

		if npc.AddImpulse and impulseMag > 0 then
			local normDir = {
				x = combined.x / impulseMag,
				y = combined.y / impulseMag,
				z = combined.z / impulseMag
			}

			-- The ragdoll needs a tick to physicalize before it accepts an
			-- impulse.
			Script.SetTimer(50, function()
				pcall(function()
					npc:AddImpulse(-1, hitPos, normDir, impulseMag, 1)
				end)
			end)
		end
	end)
end

--- Whether this collision should count as a combat one.
--
-- Two independent signals, because neither alone is reliable:
--
-- * `player.soul:IsInCombatDanger()` is what vanilla scripts use, but it
--   reflects immediate danger rather than "a fight is happening", and reads
--   false for long stretches of an ongoing fight. Mounted and moving, the
--   player may not be in danger at the instant of each impact.
-- * The victim having a weapon drawn. Townsfolk do not walk around armed, so
--   this catches the case the first signal misses: charging someone who is
--   actively fighting.
--
-- Both raw values are logged so a disagreement between them is visible
-- rather than being hidden behind a single boolean.
--
-- @tparam table npc victim entity
-- @treturn boolean true when combat rules should apply
-- @treturn string diagnostic describing both signals
function HorseCollisionMod:IsCombatCollision(npc)
	local danger = false
	local dangerOk = false
	local armed = false
	local armedOk = false

	dangerOk = pcall(function()
		if player.soul and player.soul.IsInCombatDanger then
			danger = player.soul:IsInCombatDanger()
		end
	end)

	armedOk = pcall(function()
		if npc.human and npc.human.IsWeaponDrawn then
			armed = npc.human:IsWeaponDrawn()
		end
	end)

	local detail = "danger=" .. tostring(danger) .. "/" .. tostring(dangerOk)
			.. " armed=" .. tostring(armed) .. "/" .. tostring(armedOk)

	return (danger == true or armed == true), detail
end

--- Throws the rider from the horse.
--
-- Prefers the horse's own `RearAndThrowDown`, which plays the animation of
-- the animal rearing and unseating its rider. Falls back to ragdolling the
-- player, which is what earlier builds did and which reads as the player
-- collapsing rather than being thrown.
--
-- `RearAndThrowDown` is undocumented. It sits on the horse entity's `horse`
-- extension, alongside `HasRider` and `IsMountable`.
--
-- @tparam table horseEnt the player's horse entity
-- @tparam table playerEnt the player entity
function HorseCollisionMod:ThrowRider(horseEnt, playerEnt)
	local thrown = false

	-- The method lives on the horse's own `horse` extension, found by
	-- enumerating what the entity actually carries. The other entries are
	-- kept as fallbacks in case a different mount type differs.
	local candidates = {
		{ name = "horse.horse", holder = horseEnt.horse },
		{ name = "horse", holder = horseEnt },
		{ name = "horse.actor", holder = horseEnt.actor }
	}

	for _, candidate in pairs(candidates) do
		if not thrown and candidate.holder
				and type(candidate.holder.RearAndThrowDown) == "function" then
			local ok = pcall(function()
				candidate.holder:RearAndThrowDown()
			end)

			self:Log("ThrowRider via " .. candidate.name .. " ok=" .. tostring(ok))

			if ok then
				thrown = true
			end
		end
	end

	if not thrown then
		self:Log("ThrowRider falling back to player ragdoll")

		pcall(function()
			playerEnt.actor:Fall({x=0, y=0, z=0}, true)
		end)
	end
end

--- Charges the horse for an impact and dismounts Henry when it is spent.
--
-- Stamina is written with `soul:SetState`, never `soul:DealDamage`. That
-- call takes `(stamina, health, attacker, ...)`  -  stamina first  -  even though
-- vanilla's own debug helper names the parameters health-first, so using it
-- here silently injures the horse instead.
--
-- @tparam table horseEnt the player's horse entity
-- @tparam table playerEnt the player entity
-- @tparam number staminaDrain points of stamina to remove
function HorseCollisionMod:DrainHorseStamina(horseEnt, playerEnt, staminaDrain)
	if not staminaDrain or staminaDrain <= 0 or not horseEnt or not playerEnt then
		return
	end

	pcall(function()
		if not horseEnt.soul then
			return
		end

		local before = horseEnt.soul:GetState("stamina")

		if not before then
			return
		end

		-- Clamped at zero rather than allowed to go negative, so that a
		-- single heavy impact cannot bank a deficit the horse then has to
		-- recover from before it can move again.
		local target = before - staminaDrain

		if target < 0 then
			target = 0
		end

		horseEnt.soul:SetState("stamina", target)

		self:Log("Horse stamina " .. string.format("%.1f", before)
				.. " -> " .. string.format("%.1f", target))

		if not self.Config.ThrowRiderOnStaminaEmpty then
			return
		end

		if target <= 0 and playerEnt.actor then
			self:Log("Horse spent - throwing rider.")
			self:ThrowRider(horseEnt, playerEnt)
		end
	end)
end

--- Applies the appropriate reaction for one collision.
--
-- Enforces the per-victim cooldown, then dispatches on gait.
--
-- @tparam table npc victim entity
-- @tparam table velocity horse velocity vector
-- @tparam number speed horse speed in meters per second
-- @tparam table horseEnt the player's horse entity
-- @tparam table playerEnt the player entity
-- @tparam userdata horseWuid WUID of the horse
function HorseCollisionMod:TriggerCollision(npc, velocity, speed, horseEnt, playerEnt,
		horseWuid, peakSpeed)
	local npcId = tostring(npc.id)
	local now = GetTimeMs()

	-- The detection sphere is tested ten times a second, so without a
	-- per-victim cooldown a single pass through a crowd would restart the
	-- same NPC's reaction every tick and they would never finish staggering.
	local lastHit = self.RecentHits[npcId]

	if lastHit and (now - lastHit) < self.Config.HitCooldownMs then
		self:LogRejection(npc, "cooldown",
				"since=" .. tostring(now - lastHit) .. "ms")

		return
	end

	self.RecentHits[npcId] = now

	local tierName = self:GetSpeedTier(speed)
	local strength = self.HitReactionStrength
	local cfg = self.Config
	local combatScale = 1.0
	local isCombat, combatDetail = self:IsCombatCollision(npc)

	if isCombat then
		combatScale = cfg.CombatStaminaMultiplier
	end

	self:Log("Impact tier=" .. tierName
			.. " speed=" .. string.format("%.2f", speed)
			.. " peak=" .. string.format("%.2f", peakSpeed or speed)
			.. " combatScale=" .. string.format("%.1f", combatScale)
			.. " " .. combatDetail)

	if tierName == "Walk" then
		local suppressed = cfg.SuppressStaggerInCombat and combatScale > 1.0

		if cfg.WalkStagger and not suppressed then
			self:PlayStagger(npc, velocity, speed)
		end

		self:SendHitReaction(npc, horseWuid, strength.Tickle)
		self:DrainHorseStamina(horseEnt, playerEnt, cfg.StaminaDrainWalk * combatScale)
		return
	end

	if tierName == "Trot" then
		self:Ragdoll(npc, velocity, speed, 0.6)
		self:SendHitReaction(npc, horseWuid, strength.MinorInjury)
		self:DrainHorseStamina(horseEnt, playerEnt, cfg.StaminaDrainTrot * combatScale)
		return
	end

	if tierName == "Gallop" then
		self:Ragdoll(npc, velocity, speed, 1.0)
		self:SendHitReaction(npc, horseWuid, strength.MajorInjury)
		self:DrainHorseStamina(horseEnt, playerEnt, cfg.StaminaDrainGallop * combatScale)
		return
	end
end

--- One tick of collision detection.
--
-- Bails out early unless the player is mounted and moving at least at
-- walking pace, then tests every entity within `HitRadius` of the horse.
--
-- Every engine call is wrapped in `pcall`, because entities can be unstreamed
-- or partially initialized at any moment and an uncaught error would kill the
-- timer loop for the rest of the session.
function HorseCollisionMod:SafeUpdate()
	if type(player) == "nil"
			or (not player)
			or type(player.human) == "nil"
			or type(player.player) == "nil" then
		return
	end

	local isMounted = false

	pcall(function()
		isMounted = player.human:IsMounted()
	end)

	if not isMounted then
		return
	end

	local horseWuid = nil

	pcall(function()
		horseWuid = player.player:GetPlayerHorse()
	end)

	if not horseWuid then
		return
	end

	local horseEnt = nil

	pcall(function()
		horseEnt = XGenAIModule.GetEntityByWUID(horseWuid)
	end)

	if not horseEnt then
		return
	end

	local velocity = nil

	pcall(function()
		if horseEnt.GetVelocity then
			velocity = horseEnt:GetVelocity()
		end

		if not velocity and player.GetVelocity then
			velocity = player:GetVelocity()
		end
	end)

	local speed = GetVectorLength(velocity)
	local peakSpeed = self:TrackSpeed(speed)

	-- Below walking pace nothing can happen, so the loop normally stops here
	-- before looking at a single entity. While diagnosing it keeps going, or
	-- an impact lost because the collision itself slowed the horse would leave
	-- no trace at all.
	if speed < self.Config.SpeedWalk and not self.Config.DiagnoseMisses then
		return
	end

	local horsePos = nil
	local horseForward = nil

	pcall(function()
		horsePos = horseEnt:GetPos()
	end)

	pcall(function()
		if horseEnt.GetDirectionVector then
			horseForward = horseEnt:GetDirectionVector(1)
		end
	end)

	if not horsePos or not horseForward then
		return
	end

	local hitEnts = nil

	pcall(function()
		hitEnts = System.GetEntitiesInSphere(horsePos, self.Config.HitRadius)
	end)

	if type(hitEnts) ~= "table" then
		return
	end

	for _, ent in pairs(hitEnts) do
		local isCandidate = (ent
				and type(ent) == "table"
				and ent.id
				and ent.id ~= player.id
				and ent.id ~= horseEnt.id)

		if isCandidate then
			local isMutt = false

			-- Henry's dog follows close enough to be caught constantly, and
			-- trampling him on every ride is nobody's idea of immersion. He
			-- is identified by entity name because dogs share the generic
			-- NPC class.
			pcall(function()
				local entName = ent:GetName()

				if entName and string.find(entName, "dogCompanion") then
					isMutt = true
				end
			end)

			local isProtected = (self.Config.ProtectMutt and isMutt)

			if not isProtected then
				local isHuman = false

				-- The sphere returns everything nearby: crates, doors, loose
				-- items. The faction check catches NPCs whose class is set
				-- to something unexpected, which quest characters often are.
				pcall(function()
					isHuman = (ent.class == 'NPC'
							or ent.class == 'Player'
							or (ent.Properties and ent.Properties.esFaction))
				end)

				if not isHuman then
					self:LogRejection(ent, "not-human",
							"class=" .. tostring(ent.class))
				elseif not ent.actor then
					self:LogRejection(ent, "no-actor",
							"class=" .. tostring(ent.class))
				end

				if isHuman and ent.actor then
					local isDead = false

					-- Corpses are already ragdolls. Reacting to them would
					-- twitch bodies around and re-trigger every tick.
					if ent.IsDead then
						pcall(function()
							isDead = ent:IsDead()
						end)
					end

					local inFootprint = self:IsInHorseFootprint(ent, horsePos,
							horseForward, speed)

					if isDead then
						self:LogRejection(ent, "dead", "")
					elseif not inFootprint then
						self:LogRejection(ent, "outside-footprint",
								self:FootprintDetail(ent, horsePos, horseForward, speed))
					elseif speed < self.Config.SpeedWalk then
						self:LogRejection(ent, "below-walk-speed",
								"speed=" .. string.format("%.2f", speed)
								.. " peak=" .. string.format("%.2f", peakSpeed))
					else
						self:TriggerCollision(ent, velocity, speed, horseEnt, player,
								horseWuid, peakSpeed)
					end
				end
			end
		end
	end
end

--- Reschedules itself every 100 ms and runs one detection tick.
--
-- The tick number guards against duplicate loops. Each load screen starts a
-- new loop, and any loop whose number no longer matches the current one stops
-- on its next iteration, so reloading a save leaves no stale timers running.
--
-- @tparam number assignedTick the loop generation this timer belongs to
function HorseCollisionMod:UpdateTimer(assignedTick)
	if self.TimerTick ~= assignedTick then
		return
	end

	-- The next tick is booked before any work is done. If detection ever
	-- throws in a way pcall cannot contain, the loop still survives; booking
	-- afterwards would end the mod for the rest of the session.
	Script.SetTimer(100, function()
		HorseCollisionMod:UpdateTimer(assignedTick)
	end)

	local success, err = pcall(function()
		self:SafeUpdate()
	end)

	if not success then
		self:Log("CRITICAL ERROR IN UPDATE TIMER: " .. tostring(err))
	end
end

--- Applies HorseCollisionMod_Settings.lua over the defaults above.
--
-- Settings live in their own file so that changing one does not mean finding a
-- table partway down a thousand-line script. That file ships alongside this one
-- in `Scripts/Startup/` and defines a single global.
--
-- Startup scripts are loaded in name order, so the settings file runs after
-- this one and its global does not exist at the time this file is executed.
-- The merge therefore happens from the load screen, by which point everything
-- in `Scripts/Startup/` has run.
--
-- A key that is not already in Config is rejected rather than added. Config is
-- the list of settings that exist, so an unknown key means a typo, and adding
-- it would be silently ignored by whatever was supposed to read it. A wrong
-- type is rejected for the same reason. Both are logged, because a setting that
-- quietly does nothing is worse than one that visibly fails.
--
-- @treturn number settings applied
-- @treturn number entries rejected
function HorseCollisionMod:ApplySettings()
	local settings = rawget(_G, "HorseCollisionModSettings")

	if type(settings) ~= "table" then
		return 0, 0
	end

	local applied = 0
	local rejected = 0

	for key, value in pairs(settings) do
		local current = self.Config[key]

		if current == nil then
			self:Log("Setting '" .. tostring(key) .. "' is not a setting, ignored")
			rejected = rejected + 1
		elseif type(value) ~= type(current) then
			self:Log("Setting '" .. tostring(key) .. "' wants a "
					.. type(current) .. ", got " .. type(value) .. ", ignored")
			rejected = rejected + 1
		elseif value ~= current then
			self.Config[key] = value
			applied = applied + 1
		end
	end

	return applied, rejected
end

--- Entity classes whose animation database this mod redirects.
--
-- Each entry maps an entity class table to the character set it belongs to.
--
-- Both the exposed classes and the `_x` templates they came from are listed,
-- and the distinction is the whole reason this works. `NPC_x` is a template;
-- `NPC.lua` does `NPC = CreateAI(NPC_x)`, and `CreateAI` builds a fresh table
-- and *copies* the fields in. So the live class holds a snapshot of the stock
-- paths taken when its script loaded, and redirecting only the template
-- changes nothing about what spawns.
--
-- The player class is declared
-- directly rather than through CreateAI, so redirecting it did work, which
-- made the mod's own files load and hid the fault.
-- The parent database is a few hundred bytes and holds no
-- fragments of its own; it references the untouched vanilla database inside its
-- own pak, plus this mod's fragment file.
--
-- This is what makes the mod additive. The alternative, and what 2.0.0 shipped,
-- is overriding kcd_male_database.adb outright, which means any other mod
-- touching human animations either loses its changes to this one or takes this
-- one's away depending only on mod_order.txt. Mannequin databases cannot be
-- merged, so that conflict is total and silent in both directions.
--
-- @table AnimationDatabases
HorseCollisionMod.AnimationDatabases = {
	-- The exposed classes. These are what the engine spawns, and what has to
	-- be redirected for any of this to take effect.
	NPC           = "male",
	NPC_NAI       = "male",
	NullAI        = "male",
	DummyTarget   = "male",
	Player        = "male",
	NPC_Female    = "female",
	PlayerFemale  = "female",

	-- The templates they were built from. Redirected too, so that anything
	-- calling CreateAI after this point inherits the right paths rather than
	-- the stock ones.
	NPC_x         = "male",
	NPC_NAI_x     = "male",
	NullAI_x      = "male",
	DummyTarget_x = "male",
	NPC_Female_x  = "female"
}
--- The parent database each character set uses.
--
-- Only `AnimDatabase3P` is redirected. `ActionController` deliberately is not:
-- leaving entities on vanilla's controller def means every fragment except
-- this mod's resolves through vanilla's own files, and the mod never appears
-- in the resolution path of animations it has nothing to do with.
--
-- 2.1.0 briefly redirected both, so that the stagger FragTags could live in a
-- file named hcm_*. That resolved correctly, but it also stopped the beggar
-- kneeling, because his animation resolves through BeggarIn and
-- kcd_beggar_tags.xml by way of the same copied fragment id file. The tags
-- are declared in vanilla's own tag file instead now, which is 1 KB and costs
-- nothing else its own resolution path.
--
-- @table AnimationSets
HorseCollisionMod.AnimationSets = {
	male   = "Animations/Mannequin/ADB/hcm_male_database.adb",
	female = "Animations/Mannequin/ADB/hcm_female_database.adb"
}

--- Points the human entity classes at this mod's parent databases.
--
-- AnimDatabase3P is read when an actor spawns, so this has to happen before the
-- world is populated. A Startup script runs early enough, but the entity class
-- tables are loaded on demand and may not all exist yet, hence the retry from
-- the load screen for any that were missing.
--
-- Redirecting a class twice is harmless, and a class that never appears is
-- skipped rather than treated as an error, so this is safe to call repeatedly.
--
-- @treturn number how many classes were redirected by this call
-- @treturn number how many are still waiting for their class table to exist
function HorseCollisionMod:RedirectAnimationDatabases()
	local redirected = 0
	local pending = 0

	for class, set in pairs(self.AnimationDatabases) do
		local target = rawget(_G, class)
		local database = self.AnimationSets[set]

		if type(target) ~= "table" then
			pending = pending + 1
		elseif target.AnimDatabase3P ~= database then
			target.AnimDatabase3P = database
			redirected = redirected + 1
		end
	end

	return redirected, pending
end

--- UI event handler that serves as the mod's entry point.
--
-- A Startup script has no general "game loaded" hook available to it, so the
-- end of the loading screen stands in for one.
--
-- @tparam string actionName UI action that fired
-- @tparam string eventName phase of that action
-- @tparam table argTable event arguments, unused
function HorseCollisionMod:uiActionListener(actionName, eventName, argTable)
	if actionName == "sys_loadingimagescreen" and eventName == "OnEnd" then
		HorseCollisionModGeneration = HorseCollisionModGeneration + 1

		local currentTick = HorseCollisionModGeneration

		self.TimerTick = currentTick

		local applied, rejected = self:ApplySettings()

		if applied > 0 or rejected > 0 then
			self:Log("Settings: " .. tostring(applied) .. " applied, "
					.. tostring(rejected) .. " ignored")
		end

		local again = self:RedirectAnimationDatabases()

		if again > 0 then
			self:Log("Redirected " .. tostring(again)
					.. " animation databases that loaded late")
		end

		self:Log("Load screen ended. v" .. self.Version
				.. " initializing physics timer loop "
				.. tostring(currentTick))

		Script.SetTimer(100, function()
			HorseCollisionMod:UpdateTimer(currentTick)
		end)
	end
end

-- Runs at file scope rather than from the load screen, because
-- AnimDatabase3P is read when an actor spawns and the load screen ends
-- after the world is already populated.
local hcmRedirected, hcmPending = HorseCollisionMod:RedirectAnimationDatabases()

HorseCollisionMod:Log("Redirected " .. tostring(hcmRedirected)
		.. " animation databases, " .. tostring(hcmPending) .. " pending")

if type(UIAction) == "table" and type(UIAction.RegisterActionListener) == "function" then
	UIAction.RegisterActionListener(HorseCollisionMod, "", "", "uiActionListener")
end
