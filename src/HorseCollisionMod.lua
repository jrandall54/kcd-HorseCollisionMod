--- Horse Collision Overhaul for Kingdom Come: Deliverance.
--
-- Gives mounted collisions a reaction proportional to the horse's gait. In
-- vanilla, riding into an NPC produces only an audio bark and no animation at
-- any speed. This module adds three tiers:
--
-- * **Walk** - the NPC plays a full standing stagger animation and is not
--   knocked down. No health damage, and the vanilla bark still fires.
-- * **Trot** - a physics ragdoll at reduced impulse.
-- * **Gallop** - a physics ragdoll at full impulse.
--
-- At trot and gallop the horse also loses stamina, and dismounts Henry when
-- spent. That is the anti-bulldozing budget: riding through a crowd has to
-- end with Henry on the ground rather than being a free way to scatter a
-- dozen people.
--
-- ## How the walk stagger works
--
-- Lua cannot drive an NPC's animation directly, and every obvious approach
-- fails silently: `human:PlayAnim` is accepted but never
-- renders, physics impulses are ignored because actors are animation-driven,
-- `soul:DealDamage` only moves stat numbers, and the `hitReaction` and
-- `combat:hit` brain messages reach a behavior tree that cannot drive the
-- body.
--
-- What does play a clip is `actor:StartInteractiveActionByName`, the call
-- vanilla uses to make an actor mime opening a door. It takes over the body,
-- plays a whole animation, and hands control back. Its name argument resolves
-- against the FragTags of exactly one Mannequin fragment,
-- `AnimationControlled`, where vanilla ships only object interactions.
--
-- It is not the only actor call that matters. An interactive action is
-- root-motion driven, so the animation moves the body and nothing constrains
-- where it ends up, which is why a reaction played beside a building could
-- carry its victim into the wall. `actor:SetMovementControlledByAnimation`
-- turns that off per victim, and is called a tick after the action starts;
-- see `ReleaseVictimMovement` for why the order is not negotiable.
--
-- So the mod adds its own entries there, without replacing anything. Seven
-- data files ship alongside this script, all generated by `build_adb.py`,
-- and every one is named `hcm_*` so it cannot collide with another mod:
--
-- * `hcm_<set>_database.adb` - the parent, and the authoritative definition
--   of `AnimationControlled`. It carries vanilla's own 30 options plus this
--   mod's 4, and references the untouched vanilla database as a SubADB for
--   every other fragment. Carrying vanilla's options is not optional: a
--   sub-database does not merge into a fragment another one defines, so
--   without them a redirected NPC loses every door and cabinet interaction.
-- * `hcm_<set>_fragmentids.xml` - points `AnimationControlled` at the tag
--   file below. For women it also has to declare that fragment at all,
--   since they have the same clips but no such fragment in vanilla.
-- * `hcm_<set>_controllerdefs.xml` - points its `Fragments` element at the
--   file above. This is what an entity resolves names through at runtime,
--   and redirecting the database alone is not enough.
-- * `hcm_animationControlledTags.xml` - declares those FragTags. An option
--   whose tag is not declared aborts after one frame.
-- See `docs/HOW_IT_WORKS.md` for why this indirection is worth the trouble.
--
-- ## Limitations
--
-- * Dogs and other animals do not react. They use separate animation
--   databases which this mod does not touch.
-- * Two mods redirecting `AnimDatabase3P` on the same entity class conflict.
--   The contested value is a Lua string, so a cooperative mod can chain by
--   referencing whatever is already set.
--
-- @module HorseCollisionMod
-- @author jrandall54
-- @release 4.7.4
HorseCollisionMod = {}

HorseCollisionMod.Version = "4.7.4"

--- Loop generation counter, deliberately kept outside the table above.
--
-- `lua_reload_script` re-executes this file, and its first act is to rebuild
-- HorseCollisionMod from scratch, which takes TimerTick with it. A counter
-- stored on the table therefore restarts at 1 on every reload, while any loop
-- still running from before compares its own generation against that same 1,
-- matches, and carries on. Each reload would leave another loop sweeping for
-- collisions ten times a second, all of them writing to the same cooldown
-- table.
--
-- The `or 0` is what makes this survive a reload: the global is already set by
-- then, so the count continues instead of restarting, and every stale loop
-- sees a generation that no longer matches and stops on its next tick.
HorseCollisionModGeneration = HorseCollisionModGeneration or 0

--- Tuning values. Safe to edit in place; nothing here is derived at runtime.
--
-- Grouped by what they affect, and deliberately kept terse: this is the table
-- people open to change a setting, not to read. The reasoning behind the
-- defaults is in docs/TECHNICAL_DETAILS.md under "Reaction defaults".
--
-- @field SpeedWalk lower bound of the walk tier, in meters per second
-- @field SpeedTrot lower bound of the trot tier
-- @field SpeedGallop lower bound of the gallop tier
-- @field HitRadius radius of the broad-phase sphere around the horse
-- @field HorseFrontReach how far ahead of the horse origin counts as a hit
-- @field HorseRearReach how far behind the horse origin counts as a hit
-- @field HorseHalfWidth lateral half-width of the horse footprint
-- @field HorseMaxVerticalDiff height difference above which a hit is ignored
-- @field TickSeconds detection interval, used to sweep the footprint forward
-- @field SweepMultiplier how far ahead to sweep, per meter per second
-- @field MaxSweepExtra cap on the forward sweep, in meters
-- @field HitCooldownMs minimum gap between reactions on the same victim
-- @field KnockdownRecoveryMs how long a knocked-down victim is left alone,
--   which is longer than the walk cooldown because they are still on the ground
-- @field ImpactSpeedSamples ticks of speed history a collision is scored from
-- @field MaxImpactSpeed ceiling on the speed a collision is scored at
-- @field Knockback horizontal ragdoll impulse at full strength
-- @field Uplift vertical ragdoll impulse at full strength
-- @field RagdollMass what the horse collides with, in kilograms, divided by
--   the armor scale so armor is felt as weight rather than as a force
-- @field RagdollMassArmorScaled whether RagdollMass is divided by the armor
--   scale; false gives every victim the same mass, which is how the direction
--   of the effect is read
-- @field RagdollMassArmorExponent how sharply armor is felt as weight. The
--   base cancels out of the ratio between an armored victim's mass and an
--   unarmored one, so only this widens the gap between them
-- @field ArmorReferenceWeight armor weight that scales a target by exactly one
-- @field ArmorImpulseExponent how sharply armor weight reduces the impulse
-- @field MinArmorImpulse floor on the armor impulse multiplier
-- @field MaxArmorImpulse ceiling on the armor impulse multiplier, reached by
--   an unarmored target
-- @field ArmorStaminaExponent how sharply armor weight raises the stamina cost
-- @field MinArmorStamina floor on the armor stamina multiplier
-- @field MaxArmorStamina ceiling on the armor stamina multiplier
-- @field ProtectMutt when true, Henry's dog is never a valid victim
-- @field StaminaDrainWalk horse stamina cost per victim at walk
-- @field StaminaDrainTrot horse stamina cost per victim at trot
-- @field StaminaDrainGallop horse stamina cost per victim at gallop
-- @field ThrowRiderOnStaminaEmpty dismount Henry when the horse is spent
-- @field CombatStaminaMultiplier stamina cost multiplier while in a fight
-- @field SuppressStaggerInCombat skip the stagger animation during a fight
-- @field SendHitReaction post the native brain message so barks still fire
-- @field WalkStagger whether the walk tier plays a stagger animation
-- @field SuppressAutoCureSec how often the auto-cure exemption is rechecked,
--   in seconds, or 0 to leave victims in the daycycle
-- @field TrotReaction what a trot impact does: "knockdown" for an animated
--   fall and get-up, "fall" for an animated fall the game recovers from, or
--   "ragdoll" for the physics knockdown
-- @field AutoCureHealthLimit health at or above which the auto-cure exemption
--   is dropped, matching vanilla's own limit
-- @field CollisionIsCrime whether riding someone down is reported to the
--   game as a crime, at trot and gallop
-- @field ReleaseAnimationMovement take movement control off the animation once
--   a reaction has started, so victims are not carried into walls
-- @field ReplanAfterReaction ask a victim to re-plan their activity once the
--   reaction is over, so they approach and re-align to whatever they were using
-- @field LogTelemetry write diagnostics to kcd.log
-- @field TraceRecovery time each animation state during a recovery
-- @field ImpulseDelayMs how long to wait before the ragdoll impulse
-- @field LateralImpulse how much of the impulse pushes across the
--   horse's line rather than along it
-- @field RagdollDamping how fast a thrown body sheds speed, 0 for the
--   engine's own value
-- @field RagdollMinEnergy the energy below which a body is put to rest,
--   0 for the engine's own value
-- @field DiagnoseMisses name the reason a nearby NPC produced no reaction
-- @field Retaliation whether a victim shoved repeatedly at a walk can lose
--   patience and fight back
-- @field RetaliationFreeBumps how many walk impacts a victim tolerates before
--   any chance of a fight begins
-- @field RetaliationChanceStep how much each further shove adds to the chance
-- @field RetaliationMaxChance ceiling on that chance
-- @field RetaliationMemorySec how long a victim remembers being shoved, in
--   seconds, before the count decays to nothing
-- @field RetaliationCeilingSec failsafe, in seconds, after which a watched
--   incident is closed however it looks
-- @table Config
HorseCollisionMod.Config = {
	-- Speed tiers, in meters per second. Below SpeedWalk nothing happens.
	SpeedWalk                = 1.8,
	SpeedTrot                = 4.5,
	SpeedGallop              = 8.5,

	-- Detection. HitRadius is a broad-phase sphere; everything inside it is
	-- then tested against the horse footprint, in meters from the horse
	-- origin. The sweep extends the footprint forward by one tick of travel.
	HitRadius                = 2.5,
	HorseFrontReach          = 1.05,
	HorseRearReach           = 0.20,
	HorseHalfWidth           = 0.70,
	HorseMaxVerticalDiff     = 2.35,
	TickSeconds              = 0.1,
	SweepMultiplier          = 0.50,
	MaxSweepExtra            = 0.35,
	HitCooldownMs            = 3000,
	KnockdownRecoveryMs      = 6000,

	-- A collision is scored on the peak of the last ImpactSpeedSamples ticks,
	-- not on the speed read when the victim is noticed. MaxImpactSpeed is the
	-- ceiling on that value, a little above the top of the gallop plateau.
	ImpactSpeedSamples       = 3,
	MaxImpactSpeed           = 11.0,

	-- Knockdown impulse. Trot and gallop only; the walk tier never ragdolls.
	Knockback                = 50.0,
	Uplift                   = 30.0,

	-- What the horse is hitting, in kilograms, divided by the armor scale so
	-- a man in mail is the heavier thing to move. Every human is 80 to the
	-- physics engine, which is why armor has never been felt in a throw.
	-- 0 leaves the engine's own figure alone.
	RagdollMass              = 100.0,
	RagdollMassArmorScaled   = true,

	-- How hard armor is felt as weight. The mass written is the base over the
	-- armor scale raised to this, so the ratio between an armored victim and
	-- an unarmored one is the scale ratio raised to it as well. The base
	-- cancels out of that ratio entirely, which is why 40 and 80 both left
	-- armored and unarmored victims traveling the same distance: both
	-- present the horse with the same 3.4x spread. Above 1 widens the spread;
	-- 1 is the plain division and 0 removes the scaling.
	RagdollMassArmorExponent = 3.7,

	-- What the target is wearing, as a multiplier on the impulse and on the
	-- horse's stamina cost. Both are 1.0 at ArmorReferenceWeight; an
	-- exponent of 0 switches that half off.
	ArmorReferenceWeight     = 8.0,
	ArmorImpulseExponent     = 0.5,
	MinArmorImpulse          = 0.35,
	MaxArmorImpulse          = 1.5,
	ArmorStaminaExponent     = 0.4,
	MinArmorStamina          = 0.75,
	MaxArmorStamina          = 3.0,

	-- Horse stamina, against a full pool of roughly 210.
	StaminaDrainWalk         = 0.0,
	StaminaDrainTrot         = 18.0,
	StaminaDrainGallop       = 22.0,
	ThrowRiderOnStaminaEmpty = true,

	-- How long a victim is exempted from vanilla's auto-cure daycycle,
	-- in seconds. Zero leaves them in it.
	SuppressAutoCureSec      = 30,

	-- What a trot impact does.
	--
	-- "knockdown" plays an animated fall and an animated get-up through the
	-- same path as the walk stagger, and creates no physics body, so it
	-- cannot incur the trample damage a ragdoll does.
	--
	-- "fall" plays the same fall and stops there, handing the body to a
	-- ragdoll once the clip ends so the game recovers the victim the way it
	-- recovers any fallen actor. The trample the mod moved away from is not a
	-- risk here, because the ragdoll is created several seconds after the
	-- impact rather than underneath the horse that caused it.
	--
	-- "ragdoll" is the physics knockdown the mod shipped before, created at
	-- the moment of impact.
	TrotReaction             = "fall",

	-- Whether riding someone down is a crime.
	--
	-- Sent at trot and gallop, where the collision hurts them, and never at a
	-- walk: a stagger costs no health and being arrested for brushing past
	-- someone is not the intent. The game charges it as a brawl, which is what
	-- vanilla does with a ridden collision too, and prosecutes murder on its
	-- own when a victim dies.
	CollisionIsCrime         = true,

	-- Takes movement control off the animation once a reaction has started,
	-- so the victim is moved by the entity rather than by root motion and
	-- stops being carried through walls. False restores the behavior before
	-- this, where a stagger beside a building could end inside it.
	ReleaseAnimationMovement = true,

	-- Sends a victim back to their activity once their reaction is over, so
	-- they walk to whatever they were using and are aligned to it on the way
	-- in rather than resuming it from wherever they fell.
	ReplanAfterReaction      = true,

	-- The health at or above which a victim is no longer a candidate for
	-- vanilla's auto-cure daycycle. Vanilla's own limit is 40, declared as
	-- `t_autoCureLowHealthLimit` in `Libs/AI/final/sb_daycycles.xml`. The
	-- exemption is held until the victim is back over this.
	AutoCureHealthLimit      = 40.0,

	-- Combat.
	CombatStaminaMultiplier  = 2.2,
	SuppressStaggerInCombat  = true,

	-- Retaliation. Barging the same person at a walk costs nobody anything,
	-- which makes it an annoyance rather than an act. These let a victim
	-- run out of patience: each shove is counted, and once the count passes
	-- `RetaliationFreeBumps` every further one rolls against a chance that
	-- grows with the count, up to `RetaliationMaxChance`.
	--
	-- A provoked fight is deliberately not a crime. The hit that starts it
	-- carries the engine's own `real = false`, which drives the victim's
	-- decision without reaching the reputation system, so no fine is levied
	-- and no guard is summoned. Guards who witness the brawl still join in,
	-- because they witnessed it.
	Retaliation              = true,
	RetaliationFreeBumps     = 1,
	RetaliationChanceStep    = 0.25,
	RetaliationMaxChance     = 0.85,
	RetaliationMemorySec     = 45,
	RetaliationCeilingSec    = 120,

	-- Switches.
	ProtectMutt              = true,
	WalkStagger              = true,
	SendHitReaction          = true,
	LogTelemetry             = true,

	-- Names the reason a nearby NPC produced no reaction. Every test in the
	-- detection loop rejects silently, so a missed impact and an impact that
	-- never happened look identical. Off by default: it is noisy and only
	-- useful while investigating.
	DiagnoseMisses           = false,

	-- Times every animation state a recovering victim passes through and
	-- logs the sequence. Answers where a recovery spends its seconds, which
	-- a single duration cannot. Off by default: one line per impact and a
	-- poll running for the length of each recovery.
	TraceRecovery            = false,

	-- How long to wait after the ragdoll before applying the impulse, in
	-- milliseconds.
	--
	-- An impulse applied to a body that has not physicalized yet is
	-- ignored silently, and the same magnitude has been measured throwing
	-- one victim four meters and another none at all, which is the
	-- signature of a window missed rather than of a force too small.
	ImpulseDelayMs           = 50,

	-- How much of the impulse pushes a victim sideways, against the
	-- horse's line of travel. 0 is straight along it, 1 is as much across
	-- as along.
	--
	-- A body thrown along the horse's line does not clear it. At a gallop
	-- the horse travels near ten meters a second and the impulse moves a
	-- 120 kilogram body at a fraction of that, so the horse overtakes its
	-- own victim and tramples them a second time. Pushing them across the
	-- line clears it regardless of how hard they are thrown.
	--
	-- The side is whichever one the victim is already on, so a glancing
	-- contact carries them further the way they were already going.
	LateralImpulse           = 0.0,

	-- How quickly a ragdolled victim sheds speed, and how readily it comes
	-- to rest. Both 0 leave the engine's own values alone.
	--
	-- A thrown body slides, and a slide is most of the distance an impact
	-- appears to produce. That makes distance a poor reading of force and
	-- it makes the ground feel like ice. `damping` bleeds velocity off the
	-- body and `min_energy` is the threshold below which physics puts it to
	-- rest, both fields of `pe_simulation_params`, reached through
	-- `entity:SetPhysicParams(PHYSICPARAM_SIMULATION, ...)`.
	RagdollDamping           = 3.0,
	RagdollMinEnergy         = 0.5
}


--- When each victim may react again, in milliseconds, keyed by entity id.
--
-- Holds the time a victim becomes eligible rather than the time it was last
-- hit, because how long that takes depends on what the last impact did. A
-- stagger is over quickly; a knockdown leaves them on the ground for several
-- seconds.
-- @table RecentHits
HorseCollisionMod.RecentHits = {}

--- What each victim was doing when it was hit, keyed by entity id.
--
-- Read back once the victim is on their feet, to tell one that has resumed
-- its activity from one left standing with nothing to do. A beggar and an
-- innkeeper cannot recover their own loop and need the replan; almost
-- everyone else recovers on their own and is only interrupted by it.
--
-- Cleared with the rest of the per-victim state on a load screen.
HorseCollisionMod.VictimActivity = {}




--- How often each victim has been shoved at a walk, keyed by entity id.
--
-- Each entry holds the running count and the time of the last shove, so a
-- victim barged three times in a minute is treated differently from one
-- barged three times across an afternoon. `RetaliationMemorySec` decides
-- where the line falls, and a count that has gone stale is discarded rather
-- than decremented, because a victim either still resents it or does not.
--
-- Lives in the entry point rather than in `Retaliation.lua` because the load
-- screen clears the per-victim state before any part file has a chance to
-- create its own tables.
-- @table Annoyance
HorseCollisionMod.Annoyance = {}

--- Each victim's regard for the rider before the fight, keyed by entity id.
--
-- Recorded at the moment of provocation, which is still clean: the shoves
-- that lead up to it raise no crime and the provocation names the victim as
-- his own attacker, so neither touches reputation. The repair afterwards
-- restores this figure rather than a fixed amount, because a fixed amount
-- calibrated for a ruined victim overshoots and leaves a man who was beaten
-- thinking better of the rider than he did beforehand.
-- @table Baseline
HorseCollisionMod.Baseline = {}

--- Last time each entity was reported as a miss, keyed by entity id.
HorseCollisionMod.RecentRejections = {}

--- Recent horse speeds, newest last, for spotting deceleration on impact.
--
-- Speed is sampled once per tick at the top of the loop. A collision slows the
-- horse, so if a victim only enters the footprint on the tick after contact
-- begins, the speed read is the speed after the impact rather than the speed
-- that caused it. That would explain a gallop being recorded as a walk, and it
-- would also drop the reaction entirely whenever the loss takes the horse under
-- `SpeedWalk`, because that test returns before any entity is examined.
--
-- Kept deliberately short. Half a second of history is enough to see a
-- deceleration and not so much that an earlier gallop colors a later walk.
HorseCollisionMod.SpeedHistory = {}

HorseCollisionMod.SpeedHistorySize = 10


-- How long after a reaction begins the victim is rebuilt, per tier.
--
-- Timed from the start of the reaction, because nothing here reads whether the
-- victim is still on the ground, so the figure has to cover the whole fall and
-- get-up. Too short cuts the animation; every millisecond past the end is time
-- the victim spends standing idle before their own behavior resumes.
--
-- Separate per tier because a stagger is over in about a second while a
-- knockdown runs several times longer. Not settings: once these are right
-- there is no reason for a player to hold an opinion about them.
-- How the end of a reaction is recognized, so the rebuild is triggered by an
-- observation rather than by a clock guessing at the animation's length.
--
-- `actor:GetCurrentAnimationState()` reports `AnimationControlled` for exactly
-- as long as an interactive action owns the actor, and the value it changes to
-- afterwards is an ordinary locomotion state. Leaving that value is therefore
-- the reaction ending, whatever clip played and however long it ran.
--
-- A fixed delay cannot do this job. Measured across knockdowns the state was
-- held for anywhere between 4.3 and 7.0 seconds, and a stagger released it in
-- 2.3, so any single figure lands inside the range and rebuilds some victims
-- mid-animation. Rebuilding mid-animation is worse than not rebuilding at all,
-- because the animation takes the body back afterwards and the freeze the
-- rebuild exists to prevent happens anyway.
--
-- The ceiling covers a victim who dies, unstreams, or holds the state past
-- anything observed, and the state must have been seen at least once before
-- leaving it counts, so a poll landing before the action starts cannot be
-- mistaken for the reaction already being over.
HorseCollisionMod.ReactionAnimationState = "AnimationControlled"
HorseCollisionMod.ReactionPollMs = 100
HorseCollisionMod.ReactionEndCeilingMs = 12000


-- How long after the rebuild the victim is asked to re-plan. The rebuild
-- resets the behavior and the re-plan chooses what it does next, so they are
-- ordered rather than issued together.

--- How abruptly the replan is allowed to interrupt what the victim is doing.
--
-- `daycycleHaltSpeed` in the engine's type definitions: 0 slow, 1 fast,
-- 2 instant.
--
-- Vanilla reserves `instant` for teleports and cutscenes, where the screen is
-- faded or the character is being relocated outright, and a transition with no
-- wind-down is the point. Every vanilla call site that uses it is one of those.
-- Sent to an NPC standing in the street it reads as a one-frame snap, and the
-- activity it tears down takes any prop the NPC was holding with it.
HorseCollisionMod.ReplanHaltSpeed = 1

-- When to try setting a ragdolled victim's mass, in milliseconds from the
-- moment the reaction starts. Not an LDoc item: the generator rejects a
-- documented table that carries array entries.
--
-- A ladder rather than a single delay. Mass only takes once the body is
-- physicalized, and how long that takes is not fixed; the impulse path waits
-- `ImpulseDelayMs` for the same reason and was still measured applying to a
-- body that had not finished. Each rung is tried in turn and the first that
-- reads back is kept, so the telemetry reports which one won rather than the
-- code assuming one.
--
-- The rungs are tight because the horse is the thing being raced. At ten
-- meters per second it covers a centimeter every millisecond, so a mass that
-- arrives late arrives after the collision it was meant to change.
HorseCollisionMod.RagdollMassAttemptsMs = { 0, 16, 33, 50, 80, 120 }

--- How often a provoked victim is sampled while the incident is open.
--
-- A poll interval, not a duration: it decides how promptly the mod notices a
-- fight has ended, never how long the fight is allowed to last. One second is
-- fine for a state that changes on the scale of a scuffle, and it keeps the
-- telemetry readable rather than a wall of lines.
HorseCollisionMod.RetaliationPollMs = 1000

--- Consecutive samples out of the fight before the incident is closed.
--
-- More than one, because a fighter between exchanges reads as finished for an
-- instant and closing there would cut a live fight short.
HorseCollisionMod.RetaliationSettledSamples = 3


--- The lowest a repair will leave a victim, whatever the arithmetic says.
--
-- Vanilla stops an NPC dealing with the player below 0.2, and below that he
-- decides to flee again every time he perceives the rider, which is what made
-- the damage look permanent. This sits above that rather than on it, so a
-- victim is never left balanced on the edge of it.
HorseCollisionMod.RepairFloor = 0.35

--- What losing the fight costs a victim permanently.
--
-- The repair deliberately does not restore a victim to exactly what he was.
-- He was ridden down and then beaten, and remembering it is correct; what is
-- not correct is being ruined for good. So the target is his own standing
-- less this, held above the floor above, which leaves a man who thinks less
-- of the rider than his neighbors do and still trades with him.
HorseCollisionMod.RepairFightCost = 0.15

--- How far one `surrender_step` moves a relationship.
--
-- Measured by applying it repeatedly from zero and reading between each: the
-- move is exactly 0.1389 every time, and the second argument the bind accepts
-- does not scale it. 0.1, 0.2 and no argument at all all produced the same
-- figure, so the count of applications is the only control there is.
--
-- `surrender_step` also cannot carry anyone past 0.8430, which the same sweep
-- reached and then stopped at.
HorseCollisionMod.RepairStepValue = 0.1389

--- A ceiling on the applications any single repair will make.
--
-- Nothing legitimate needs more: a victim at 0.0 restored to a townsman's
-- 0.35 takes three. It bounds a victim whose relationship cannot be read.
HorseCollisionMod.RepairMaxSteps = 5

--- How long after stopping him his standing is checked a second time.
HorseCollisionMod.AftermathSettleMs = 8000

--- The standing assumed for a victim nothing was recorded for.
--
-- Untouched townsmen sampled across a village all read 0.50.
HorseCollisionMod.RepairDefaultTarget = 0.50

--- How often a provoked victim is checked for having entered the fight.
--
-- Faster than the incident poll above, because this one is racing a victim
-- who is standing still and not fighting: every quarter second he spends in
-- a guard he was never going to break out of is a quarter second the shove
-- reads as having done nothing.
HorseCollisionMod.RetaliationReleaseMs = 250

--- How many of those checks are made before giving up on the release.
--
-- Twenty at a quarter second is five seconds, which is far longer than the
-- behavior tree takes to reach the fight subtree. Bounded so a victim who
-- never arrives, because the provocation was refused or he was interrupted,
-- cannot leave a timer running for the rest of the session.
HorseCollisionMod.RetaliationReleaseTries = 20


-- How the ragdoll handover is watched, for the tier that hands recovery back
-- to the game. `GetPhysicalizationProfile` reads `alive` throughout a ragdoll
-- and cannot be used; the animation state does report `BlendRagdoll`.
--
-- The ceiling is generous because this waits on the game's own recovery rather
-- than on a clip of known length.
HorseCollisionMod.RagdollAnimationState = "BlendRagdoll"
HorseCollisionMod.RagdollResolveCeilingMs = 15000


--- Applies HorseCollisionMod_Settings.lua over the defaults above.
--
-- Settings live in their own file so that changing one does not mean opening
-- the mod's source at all. That file ships alongside this one in
-- `Scripts/Startup/` and defines a single global.
--
-- Startup scripts are loaded in name order, so the settings file runs after
-- this one and its global does not exist at the time this file is executed.
-- The merge therefore happens from the load screen, by which point everything
-- in `Scripts/Startup/` has run.
--
-- A key that is not already in Config is rejected rather than added. Config is
-- the list of settings that exist, so an unknown key means a typo, and adding
-- it would be silently ignored by whatever was supposed to read it. A wrong
-- type is rejected for the same reason. Both are logged, because a setting that
-- quietly does nothing is worse than one that visibly fails.
--
-- @treturn number settings applied
-- @treturn number entries rejected
function HorseCollisionMod:ApplySettings()
	local settings = rawget(_G, "HorseCollisionModSettings")

	if type(settings) ~= "table" then
		return 0, 0
	end

	local applied = 0
	local rejected = 0

	for key, value in pairs(settings) do
		local current = self.Config[key]

		if current == nil then
			self:Log("Setting '" .. tostring(key) .. "' is not a setting, ignored")
			rejected = rejected + 1
		elseif type(value) ~= type(current) then
			self:Log("Setting '" .. tostring(key) .. "' wants a "
					.. type(current) .. ", got " .. type(value) .. ", ignored")
			rejected = rejected + 1
		elseif value ~= current then
			self.Config[key] = value
			applied = applied + 1
		end
	end

	return applied, rejected
end

-- Entity classes whose animation database this mod redirects.
--
-- Documented as an ordinary comment rather than an LDoc block, for the reason
-- given on ImpactProbeSamples above: LDoc reads an annotated table as a set of
-- named fields, and one that only maps class names to a character set carries
-- nothing a per-field line would add.
--
-- Each entry maps an entity class table to the character set it belongs to.
--
-- Both the exposed classes and the `_x` templates they came from are listed,
-- and the distinction is the whole reason this works. `NPC_x` is a template;
-- `NPC.lua` does `NPC = CreateAI(NPC_x)`, and `CreateAI` builds a fresh table
-- and *copies* the fields in. So the live class holds a snapshot of the stock
-- paths taken when its script loaded, and redirecting only the template
-- changes nothing about what spawns.
--
-- The player class is declared
-- directly rather than through CreateAI, so redirecting it did work, which
-- made the mod's own files load and hid the fault.
-- The parent database is a few hundred bytes and holds no
-- fragments of its own; it references the untouched vanilla database inside its
-- own pak, plus this mod's fragment file.
--
-- This is what makes the mod additive. The alternative, and what 2.0.0 shipped,
-- is overriding kcd_male_database.adb outright, which means any other mod
-- touching human animations either loses its changes to this one or takes this
-- one's away depending only on mod_order.txt. Mannequin databases cannot be
-- merged, so that conflict is total and silent in both directions.
--
HorseCollisionMod.AnimationDatabases = {
	-- The exposed classes. These are what the engine spawns, and what has to
	-- be redirected for any of this to take effect.
	NPC           = "male",
	NPC_NAI       = "male",
	NullAI        = "male",
	DummyTarget   = "male",
	Player        = "male",
	NPC_Female    = "female",
	PlayerFemale  = "female",

	-- The templates they were built from. Redirected too, so that anything
	-- calling CreateAI after this point inherits the right paths rather than
	-- the stock ones.
	NPC_x         = "male",
	NPC_NAI_x     = "male",
	NullAI_x      = "male",
	DummyTarget_x = "male",
	NPC_Female_x  = "female"
}
--- The parent database each character set uses.
--
-- Only `AnimDatabase3P` is redirected. `ActionController` deliberately is not:
-- leaving entities on vanilla's controller def means every fragment except
-- this mod's resolves through vanilla's own files, and the mod never appears
-- in the resolution path of animations it has nothing to do with.
--
-- Redirecting `ActionController` as well would let the stagger FragTags live
-- in a file named hcm_*, and it resolves correctly, but it puts a copied
-- fragment id file in the path of unrelated animations: the beggar's kneeling
-- resolves through BeggarIn and kcd_beggar_tags.xml by way of that same file,
-- and stops. The FragTags are declared in vanilla's own tag file instead,
-- which is 1 KB and costs no other animation its resolution path.
--
-- @table AnimationSets
HorseCollisionMod.AnimationSets = {
	male   = "Animations/Mannequin/ADB/hcm_male_database.adb",
	female = "Animations/Mannequin/ADB/hcm_female_database.adb"
}

--- Points the human entity classes at this mod's parent databases.
--
-- AnimDatabase3P is read when an actor spawns, so this has to happen before the
-- world is populated. A Startup script runs early enough, but the entity class
-- tables are loaded on demand and may not all exist yet, hence the retry from
-- the load screen for any that were missing.
--
-- Redirecting a class twice is harmless, and a class that never appears is
-- skipped rather than treated as an error, so this is safe to call repeatedly.
--
-- @treturn number how many classes were redirected by this call
-- @treturn number how many are still waiting for their class table to exist
function HorseCollisionMod:RedirectAnimationDatabases()
	local redirected = 0
	local pending = 0

	for class, set in pairs(self.AnimationDatabases) do
		local target = rawget(_G, class)
		local database = self.AnimationSets[set]

		if type(target) ~= "table" then
			pending = pending + 1
		elseif target.AnimDatabase3P ~= database then
			target.AnimDatabase3P = database
			redirected = redirected + 1
		end
	end

	return redirected, pending
end

--- UI event handler that serves as the mod's entry point.
--
-- A Startup script has no general "game loaded" hook available to it, so the
-- end of the loading screen stands in for one.
--
-- @tparam string actionName UI action that fired
-- @tparam string eventName phase of that action
-- @tparam table argTable event arguments, unused
function HorseCollisionMod:uiActionListener(actionName, eventName, argTable)
	if actionName == "sys_loadingimagescreen" and eventName == "OnEnd" then
		HorseCollisionModGeneration = HorseCollisionModGeneration + 1

		local currentTick = HorseCollisionModGeneration

		self.TimerTick = currentTick

		-- Cooldown deadlines are stamped against a clock the save restores,
		-- and the entity ids keying them are reused across a load. Neither
		-- survives the transition, so the table is dropped rather than
		-- carried into a world it no longer describes.
		self.RecentHits = {}
		self.VictimActivity = {}
		self.Annoyance = {}
		self.Baseline = {}

		local applied, rejected = self:ApplySettings()

		if applied > 0 or rejected > 0 then
			self:Log("Settings: " .. tostring(applied) .. " applied, "
					.. tostring(rejected) .. " ignored")
		end

		local again = self:RedirectAnimationDatabases()

		if again > 0 then
			self:Log("Redirected " .. tostring(again)
					.. " animation databases that loaded late")
		end

		self:Log("Load screen ended. v" .. self.Version
				.. " initializing physics timer loop "
				.. tostring(currentTick))

		Script.SetTimer(100, function()
			HorseCollisionMod:UpdateTimer(currentTick)
		end)
	end
end

-- The rest of the mod, named explicitly and in the order it is wanted.
--
-- `Script.ReloadScript` is how the base game composes its own Lua: it is the
-- first line of nearly every vanilla entity script and is what
-- `Scripts/common.lua` uses to pull in its utility files. It is synchronous
-- and resolves the path through the merged pak filesystem, so a part file is
-- fully defined by the time the next line runs.
--
-- The parts live outside `Scripts/Startup/` on purpose. The engine enumerates
-- that folder and executes what it finds, in no guaranteed order, which would
-- both run a part before this table exists and run it a second time. Only the
-- entry point is enumerated; everything else is named here.
--
-- Loaded at the foot of the file rather than the head so that every part can
-- rely on the whole entry point being defined, and so the bootstrap below,
-- which calls into the mod, runs after the parts are in place. Each part adds
-- to the table above and carries no top-level statements, so the reload the
-- dev console fires cascades through them harmlessly.
Script.ReloadScript("Scripts/HorseCollisionMod/Enums.lua")
Script.ReloadScript("Scripts/HorseCollisionMod/Log.lua")
Script.ReloadScript("Scripts/HorseCollisionMod/Armor.lua")
Script.ReloadScript("Scripts/HorseCollisionMod/Detection.lua")
Script.ReloadScript("Scripts/HorseCollisionMod/Health.lua")
Script.ReloadScript("Scripts/HorseCollisionMod/Reaction.lua")
Script.ReloadScript("Scripts/HorseCollisionMod/Recovery.lua")
