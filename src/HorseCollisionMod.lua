--- Loop generation counter, deliberately kept outside the table above.
--
-- `lua_reload_script` re-executes this file, which rebuilds HorseCollisionMod
-- from scratch and takes TimerTick with it. A counter stored on the table
-- would restart at 1 on every reload, and a loop still running from before
-- would match that 1 and carry on, leaving one more detection loop per
-- reload.
--
-- The global survives the reload, so the count continues, and every stale
-- loop sees a generation that does not match and stops on its next tick.
