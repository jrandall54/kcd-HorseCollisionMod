--- Horse Collision Overhaul for Kingdom Come: Deliverance.
--
-- Gives mounted collisions a reaction proportional to the horse's gait. In
-- vanilla, riding into an NPC produces only an audio bark and no animation at
-- any speed. This module adds five tiers, three from the horse's speed and
-- two from commanded moves:
--
-- * **Walk** - a standing stagger. No health damage.
-- * **Trot** - an animated fall that hands the body to a ragdoll.
-- * **Gallop** - a physics ragdoll at the moment of contact.
-- * **Rear** - the hooves coming down on whoever is in front; a fall.
-- * **Charge** - a lunge out of a rear that throws its victim in ragdoll.
--
-- Every tier but the walk costs the horse stamina, and a spent horse
-- dismounts Henry. That is the anti-bulldozing budget: riding through a crowd
-- ends with Henry on the ground rather than being a free way to scatter a
-- dozen people.
--
-- ## How the walk stagger works
--
-- Lua cannot drive an NPC's animation directly, and every obvious approach
-- fails silently: `human:PlayAnim` is accepted but never
-- renders, physics impulses are ignored because actors are animation-driven,
-- `soul:DealDamage` only moves stat numbers, and the `hitReaction` and
-- `combat:hit` brain messages reach a behavior tree that cannot drive the
-- body.
--
-- What does play a clip is `actor:StartInteractiveActionByName`, the call
-- vanilla uses to make an actor mime opening a door. It takes over the body,
-- plays a whole animation, and hands control back. Its name argument resolves
-- against the FragTags of exactly one Mannequin fragment,
-- `AnimationControlled`, where vanilla ships only object interactions.
--
-- An interactive action is root-motion driven, so the animation moves the
-- body and nothing constrains where it ends up; a reaction played beside a
-- building would carry its victim into the wall.
-- `actor:SetMovementControlledByAnimation` turns that off per victim, a tick
-- after the action starts; see `ReleaseActorMovement` for why the order
-- matters.
--
-- The mod adds its own options to that fragment without replacing anything.
-- Six data files ship alongside this script:
--
-- * `hcm_male_database.adb`, `hcm_female_database.adb` - generated by
--   `build_adb.py`. Each is the parent and the authoritative definition of
--   `AnimationControlled`: vanilla's own options plus this mod's, with the
--   untouched vanilla database referenced as a SubADB for every other
--   fragment. Carrying vanilla's options is required: a sub-database does not
--   merge into a fragment another one defines, so without them a redirected
--   NPC loses every door and cabinet interaction.
-- * `kcd_animationControlledTags.xml` - generated. Vanilla's tag file under
--   its own name, with this mod's FragTags added. An option whose tag is not
--   declared aborts after one frame.
-- * `hcm_horse_database.adb`, `kcd_horse_fragmentids.xml`,
--   `kcd_horse_controllerdefs.xml` - hand authored. They give the horse an
--   `AnimationControlled` fragment carrying the two rears.
--
-- See `docs/HOW_IT_WORKS.md` for the layout in full.
--
-- ## Limitations
--
-- * Dogs and other animals do not react. They use separate animation
--   databases which this mod does not touch.
-- * Two mods redirecting `AnimDatabase3P` on the same entity class conflict.
--   The contested value is a Lua string, so a cooperative mod can chain by
--   referencing whatever is already set.
--
