--- The parent database each character set uses.
--
-- Only `AnimDatabase3P` is redirected. `ActionController` deliberately is not:
-- leaving entities on vanilla's controller def means every fragment except
-- this mod's resolves through vanilla's own files, and the mod never appears
-- in the resolution path of animations it has nothing to do with.
--
-- Redirecting `ActionController` as well would let the reaction FragTags live
-- in a file named hcm_*, but it puts a copied fragment id file in the path of
-- unrelated animations, which then stop playing: the beggar's kneeling
-- resolves through BeggarIn and kcd_beggar_tags.xml by way of that same file.
-- The FragTags are declared in vanilla's own tag file instead, which is 1 KB
-- and costs no other animation its resolution path.
--
-- @table AnimationSets
HorseCollisionMod.AnimationSets = {
	male   = "Animations/Mannequin/ADB/hcm_male_database.adb",
	female = "Animations/Mannequin/ADB/hcm_female_database.adb",
	horse  = "Animations/Mannequin/ADB/hcm_horse_database.adb"
}

--- Points the redirected entity classes at this mod's parent databases.
--
-- AnimDatabase3P is read when an actor spawns, so this has to happen before the
-- world is populated. A Startup script runs early enough, but the entity class
-- tables are loaded on demand and may not all exist yet, hence the retry from
-- the load screen for any that were missing.
--
-- Redirecting a class twice is harmless, and a class that never appears is
-- skipped rather than treated as an error, so this is safe to call repeatedly.
--
-- @treturn number how many classes were redirected by this call
-- @treturn number how many are still waiting for their class table to exist
function HorseCollisionMod:RedirectAnimationDatabases()
	local redirected = 0
	local pending = 0

	for class, set in pairs(self.AnimationDatabases) do
		local target = rawget(_G, class)
		local database = self.AnimationSets[set]

		if type(target) ~= "table" then
			pending = pending + 1
		elseif target.AnimDatabase3P ~= database then
			target.AnimDatabase3P = database
			redirected = redirected + 1
		end
	end

	return redirected, pending
end

--- UI event handler that serves as the mod's entry point.
--
-- A Startup script has no general "game loaded" hook available to it, so the
-- end of the loading screen stands in for one.
--
-- @tparam string actionName UI action that fired
-- @tparam string eventName phase of that action
-- @tparam table argTable event arguments, unused
function HorseCollisionMod:uiActionListener(actionName, eventName, argTable)
	if HorseCollisionModListenerInstance and self ~= HorseCollisionModListenerInstance then
		return
	end

	if actionName == "igm_inventory" then
		if eventName == "OnStart" then
			self.InventoryOpen = true
		elseif eventName == "OnEnd" then
			self.InventoryOpen = false
			self:QueueNextTutorial()
		end
	end

	if actionName == "sys_loadingimagescreen" and eventName == "OnEnd" then
		HorseCollisionModGeneration = HorseCollisionModGeneration + 1

		local currentTick = HorseCollisionModGeneration

		self.TimerTick = currentTick

		-- Contact stamps are written against a clock the save restores, and
		-- the entity ids keying them are reused across a load. Neither
		-- survives the transition, so the tables are dropped rather than
		-- carried into a world they do not describe.
		self.LastScoredHit = {}
		self.StandingHead = {}
		self.LockedUntil = {}
		self.RecentRejections = {}
		self.RecentBarks = {}
		self.RecentHushes = {}
		self.SphereCache = { pos = nil, ents = nil, at = 0 }

		-- Every deadline below is stamped against `System.GetCurrTime`, which
		-- is level time: loading a save winds it back to the moment the save
		-- was written, so a deadline set before the save would still be in the
		-- future in the world that comes back. Each is cleared.
		self.RearNextAt = nil
		self.ChargeNextAt = nil

		-- The move-in-progress marks also have their clearing timers dropped
		-- by the generation change, so a save written mid-charge would
		-- refuse every press.
		self.RearBusyUntil = nil
		self.RearCharging = false

		-- The charge's stand-aside window is a deadline on the same clock.
		-- Left in place, it holds the detection loop off every walk, trot and
		-- gallop impact until the restored clock passes it.
		self.ChargeScoringUntil = nil

		-- The lean's re-base guard, `LeanHomeUntil`, is a deadline on the same
		-- clock. `LeanHeld` is dropped too, since a save written mid-lean would
		-- otherwise come back holding a sign that nothing can release,
		-- permanently refusing `StartLean`.
		self.LeanHomeUntil = nil
		self.LeanHeld = nil
		self.LeanLastFlip = nil
		self.LeanGeneration = (self.LeanGeneration or 0) + 1

		self.VictimActivity = {}
		self.SurrenderHintFor = {}
		self.Annoyance = {}
		self.WasMounted = false

		-- A hint showing when the game was saved would come back with the
		-- save and never be taken down, since the fight that raised it is
		-- gone.
		self:HideSurrenderHint(true)
		self.Baseline = {}

		local applied, rejected = self:ApplySettings()

		if applied > 0 or rejected > 0 then
			self:Log("Settings: " .. tostring(applied) .. " applied, "
					.. tostring(rejected) .. " ignored")
		end

		if self.SyncTutorialsOnLoad then
			self:SyncTutorialsOnLoad()
		end

		self:HookRearKey()
		self:LoadRearActionMap()

		local again = self:RedirectAnimationDatabases()

		if again > 0 then
			self:Log("Redirected " .. tostring(again)
					.. " animation databases that loaded late")
		end

		self:Log("Load screen ended. v" .. self.Version
				.. " initializing physics timer loop "
				.. tostring(currentTick))

		Script.SetTimer(self:TickMs(), function()
			HorseCollisionMod:UpdateTimer(currentTick)
		end)
	end
end

