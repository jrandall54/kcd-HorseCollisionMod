	NPC           = "male",
	NPC_NAI       = "male",
	NullAI        = "male",
	DummyTarget   = "male",
	NPC_Female    = "female",

	-- The templates they were built from. Redirected too, so that anything
	-- calling CreateAI after this point inherits the right paths rather than
	-- the stock ones.
	NPC_x         = "male",
	NPC_NAI_x     = "male",
	NullAI_x      = "male",
	DummyTarget_x = "male",
	NPC_Female_x  = "female",

	-- The horse, so a rear can be asked for. Its vanilla database has no
	-- `AnimationControlled` fragment at all, which is the only fragment
	-- `StartInteractiveActionByName` can reach.
	Horse         = "horse"
